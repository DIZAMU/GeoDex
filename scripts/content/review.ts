/**
 * Writes content/REVIEW.md: every fact with `verified: false`, grouped by module and group,
 * so the author can check them. Deterministic.
 */
import { existsSync, readdirSync, readFileSync, writeFileSync } from "node:fs";
import type { CitiesFile, CountriesFile } from "../../src/data/types.ts";
import type { ContentGroupFile } from "../../src/engine/explain/types.ts";

export function reviewMarkdown(
  root = "content",
  countriesPath = "data/countries.json",
  citiesPath = "data/cities.json",
): string {
  const countries = JSON.parse(readFileSync(countriesPath, "utf8")) as CountriesFile;
  const cities = existsSync(citiesPath)
    ? (JSON.parse(readFileSync(citiesPath, "utf8")) as CitiesFile).cities
    : [];
  const names = new Map([
    ...countries.countries.map((c) => [c.id, c.names.en] as const),
    ...cities.map((c) => [c.id, c.names.en] as const),
    ...(existsSync("data/landmarks.json")
      ? (
          JSON.parse(readFileSync("data/landmarks.json", "utf8")) as {
            landmarks: { id: string; names: { en: string } }[];
          }
        ).landmarks.map((l) => [l.id, l.names.en] as const)
      : []),
  ]);
  const continentNames: Record<string, string> = {
    africa: "Africa",
    asia: "Asia",
    europe: "Europe",
    north_america: "North America",
    south_america: "South America",
    oceania: "Oceania",
  };
  const subregions = new Map(countries.subregions.map((s) => [s.id, s.names.en]));
  const lines = [
    "# Content review",
    "",
    "Generated by `pnpm content:review`. Every fact marked `verified: false`, grouped by module and group. Check each claim (and its source when it has one) in both languages, then set `verified: true` in the content file and regenerate.",
    "",
  ];
  let total = 0;
  for (const [module, heading, groupName] of [
    ["countries", "Countries", (id: string) => subregions.get(id) ?? id],
    ["cities", "Cities", (id: string) => continentNames[id] ?? id],
    ["landmarks", "Landmarks", (id: string) => continentNames[id] ?? id],
  ] as const) {
    const dir = `${root}/entities/${module}`;
    const files = existsSync(dir)
      ? readdirSync(dir)
          .filter((f) => f.endsWith(".json"))
          .sort()
      : [];
    if (files.length === 0) continue;
    lines.push(`## ${heading}`, "");
    for (const file of files) {
      const group = JSON.parse(readFileSync(`${dir}/${file}`, "utf8")) as ContentGroupFile;
      const rows: string[] = [];
      for (const e of group.entities) {
        for (const f of e.facts) {
          if (f.verified) continue;
          total += 1;
          rows.push(`- **${names.get(e.entityId) ?? e.entityId}** \`${f.id}\` (tier ${f.tier})`);
          rows.push(`  - en: ${f.text.en}`);
          rows.push(`  - nb: ${f.text.nb}`);
          if (f.sourceUrl) rows.push(`  - source: ${f.sourceUrl}`);
        }
      }
      if (rows.length === 0) continue;
      lines.push(`### ${groupName(group.group)}`, "", ...rows, "");
    }
  }
  const groupsPath = `${root}/groups.json`;
  if (existsSync(groupsPath)) {
    const { notes } = JSON.parse(readFileSync(groupsPath, "utf8")) as {
      notes: Record<string, { text: { en: string; nb: string }; verified: boolean }>;
    };
    const groupNames = existsSync("data/curated/groups.json")
      ? new Map(
          (
            JSON.parse(readFileSync("data/curated/groups.json", "utf8")) as {
              groups: { id: string; names: { en: string } }[];
            }
          ).groups.map((g) => [g.id, g.names.en]),
        )
      : new Map<string, string>();
    const rows = Object.entries(notes)
      .filter(([, n]) => !n.verified)
      .flatMap(([id, n]) => [
        `- **${groupNames.get(id) ?? id}** \`${id}\``,
        `  - en: ${n.text.en}`,
        `  - nb: ${n.text.nb}`,
      ]);
    total += rows.length / 3;
    if (rows.length > 0) lines.push("## Groups of countries", "", ...rows, "");
  }
  lines.splice(4, 0, `${total} facts to review.`, "");
  return `${lines.join("\n").trimEnd()}\n`;
}

if (import.meta.main) {
  writeFileSync("content/REVIEW.md", reviewMarkdown());
  console.log("Wrote content/REVIEW.md.");
}
