/**
 * Norwegian read-through list. Compares src/i18n/nb.json with
 * the same file at a release tag and writes every new and changed Norwegian string, with the
 * English next to it, to NB-REVIEW.md (not committed). The owner reads the list before a release.
 *
 * Usage: node scripts/content/nb-review.ts [tag]   (default v1.0.0)
 */
import { execFileSync } from "node:child_process";
import { readFileSync, writeFileSync } from "node:fs";

type Tree = { [key: string]: string | Tree };

function flatten(tree: Tree, prefix = ""): Map<string, string> {
  const out = new Map<string, string>();
  for (const [key, value] of Object.entries(tree)) {
    const path = prefix ? `${prefix}.${key}` : key;
    if (typeof value === "string") out.set(path, value);
    else for (const [k, v] of flatten(value, path)) out.set(k, v);
  }
  return out;
}

const tag = process.argv[2] ?? "v1.0.0";
const before = flatten(
  JSON.parse(execFileSync("git", ["show", `${tag}:src/i18n/nb.json`], { encoding: "utf8" })),
);
const nb = flatten(JSON.parse(readFileSync("src/i18n/nb.json", "utf8")));
const en = flatten(JSON.parse(readFileSync("src/i18n/en.json", "utf8")));

const added = [...nb].filter(([key]) => !before.has(key));
const changed = [...nb].filter(([key, value]) => before.has(key) && before.get(key) !== value);
const removed = [...before.keys()].filter((key) => !nb.has(key));

const cell = (s: string | undefined) => (s ?? "").replace(/\|/g, "\\|").replace(/\n/g, " ");
const table = (rows: [string, string][], showOld: boolean) =>
  rows.length === 0
    ? "None.\n"
    : `${[
        showOld ? "| Key | Norwegian now | Before | English |" : "| Key | Norwegian | English |",
        showOld ? "| --- | --- | --- | --- |" : "| --- | --- | --- |",
        ...rows.map(([key, value]) =>
          showOld
            ? `| \`${key}\` | ${cell(value)} | ${cell(before.get(key))} | ${cell(en.get(key))} |`
            : `| \`${key}\` | ${cell(value)} | ${cell(en.get(key))} |`,
        ),
      ].join("\n")}\n`;

writeFileSync(
  "NB-REVIEW.md",
  `# Norwegian strings to read

Generated by \`node scripts/content/nb-review.ts ${tag}\`. Do not edit by hand; fix the
strings in src/i18n/nb.json and run the script again.

Every Norwegian interface string that is new or changed since ${tag}: ${added.length} new,
${changed.length} changed, ${removed.length} removed. Read each one in context if you can
(the key says where it appears). Things to look for: natural word order, «» for quotes,
sentence case, the same plain register as the English, and numbers that read well.

## New (${added.length})

${table(added, false)}
## Changed (${changed.length})

${table(changed, true)}
## Removed (${removed.length})

${removed.length === 0 ? "None." : removed.map((k) => `\`${k}\``).join(", ")}
`,
);
console.log(
  `${added.length} new, ${changed.length} changed, ${removed.length} removed. Wrote NB-REVIEW.md`,
);
